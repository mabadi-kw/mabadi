NUM = r'\(?\s*\d+\s*\)?(?:\s*/\s*\d+|\s*/\s*[أ-ي]\b)?(?:\s*مكرر(?:اً|ا|ًا)?(?:\s*\(?[أ-ي]\)?)?)?'
ART = rf'(?:{NUM}|{ORD_RE})'
SEP = r'\s*(?:،|,|و|-|–)\s*'
RANGE = r'\s*(?:حتى|إلى|الى|إلي|وحتى)\s*'
ARTLIST = rf'{ART}(?:(?:{SEP}|{RANGE}){ART})*'
HEAD = r'(?:(?:[وف]?(?:لل|بال|ال))ماد(?:ة|تان|تين)|(?:[وف]?(?:لل|بال|ال))مواد(?:\s+أرقام|\s+رقم)?(?:\s+من)?|م\.?)'
ARTSPEC = re.compile(rf'(?<![أ-ي])(?P<head>{HEAD})\s*(?:رقم\s*)?(?P<arts>{ARTLIST})')

LAWNUM = re.compile(r'^\s*(?:،\s*)?(?:والفقرة[^.،]{0,20}?)?(?:من\s+|في\s+)?(?:ذات\s+|نفس\s+)?'
                    r'(?:(?:ال)?(?:مرسوم\s*(?:ب(?:ال)?قانون|الأميري)?|أمر\s+أميري(?:\s+ب(?:ال)?قانون)?|قانون|ق\.?)\s*)'
                    r'(?:رقم\s*)?\(?\s*(?P<n>\d+)\s*\)?\s*(?:لسنة|لسنه|/|س)\s*(?P<y>\d{4})')
LAWNUM_FREE = re.compile(r'(?:(?:ال)?(?:مرسوم\s*(?:ب(?:ال)?قانون|الأميري)?|أمر\s+أميري(?:\s+ب(?:ال)?قانون)?|القانون|قانون)\s*)'
                         r'(?:رقم\s*)?\(?\s*(?P<n>\d+)\s*\)?\s*(?:لسنة|لسنه)\s*(?P<y>\d{4})')
LAWNUM2 = re.compile(r'^\s*(?:من\s+)?(?:ال)?(?:قانون|مرسوم\s*ب(?:ال)?قانون)\s+[^.،\d]{3,70}?\s*(?:رقم|ق\.?)\s*\(?\s*(?P<n>\d+)\s*\)?\s*(?:لسنة|لسنه|/)\s*(?P<y>\d{4})')
CONTEXT = re.compile(r'^\s*(?:من\s+)?(?:ذات\s+القانون|نفس\s+القانون|القانون\s+(?:ذاته|نفسه|سالف\s+(?:الذكر|البيان)|المشار\s+إليه|المذكور)|منه\b|من\s+هذا\s+القانون)')
NAMED_RE = [(re.compile(rf'^\s*(?:من\s+)?(?:{p})'), k, n) for p, k, n in NAMED]

def parse_arts(s, singular=False):
    out = []
    parts = re.split(rf'({RANGE})', s)
    toks = re.findall(rf'{ORD_RE}|\d+(?:\s*/\s*(?:\d+|[أ-ي]\b))?(?:\s*مكرر(?:اً|ا|ًا)?)?', s)
    rng = re.search(RANGE, s) is not None
    for t in toks:
        if t in ORD: t = str(ORD[t])
        t = re.sub(r'\s+', '', t)
        out.append(t)
    # «المادة 116/2 و3» — مادة واحدة بفقرتين
    if singular and out and '/' in out[0] and re.match(r'\d+/\d+$', out[0]):
        base = out[0].split('/')[0]
        out = [out[0]] + [f'{base}/{t}' if t.isdigit() and int(t) < 10 else t for t in out[1:]]
    if rng and len(out) == 2 and out[0].isdigit() and out[1].isdigit() and 0 < int(out[1]) - int(out[0]) < 60:
        out = [str(i) for i in range(int(out[0]), int(out[1]) + 1)]
    return out

def lawname_after(text, end):
    m = re.match(r'\s*(?:المعدل[^.،]{0,40}?)?\s*(?:في\s+شأن|بشأن|بإنشاء|بإصدار|بقانون)\s+([^.،"(]{3,70})', text[end:])
    if m:
        n = re.split(r'\s+(?:على|أن|ان|من|وإذ|وكان|فإن|والمعدل|المعدل|يدل|مفاده)\s', m.group(1))[0].strip(' -–')
        return n
    return None

def extract(text):
    refs = []          # {law, name, articles, method, raw}
    last = None        # آخر قانون مذكور (للإحالة السياقية)
    events = []
    for m in ARTSPEC.finditer(text):
        arts = parse_arts(m.group('arts'))
        if not arts: continue
        tail = text[m.end():m.end() + 140]
        law = name = method = None; rawend = m.end()
        lm = LAWNUM.match(tail)
        if lm:
            law = f"{int(lm.group('n'))}/{lm.group('y')}"; method = 'explicit'; rawend = m.end() + lm.end()
            name = CANON.get(law) or lawname_after(text, rawend)
        else:
            for rx, k, n in NAMED_RE:
                nm = rx.match(tail)
                if nm:
                    # «مدني» وحدها لا تُقبل إلا مباشرة بعد رقم المادة (مثل: المادة 446 مدني)
                    if k == '67/1980' and nm.group(0).strip() == 'مدني' and not re.match(r'^\s*مدني', tail): continue
                    law, name, method = k, n, 'named'; rawend = m.end() + nm.end(); break
            if not law:
                cm = CONTEXT.match(tail)
                if cm and last:
                    law, name, method = last[0], last[1], 'context'; rawend = m.end() + cm.end()
        events.append((m.start(), law, name))
        if law:
            refs.append({'law': law, 'name': name, 'articles': arts, 'method': method, 'raw': text[m.start():rawend].strip()})
            last = (law, name)
        # قوانين مذكورة بين هذه الإحالة والتالية تحدّث «آخر قانون»
    # إحالات إلى قانون دون مادة (تُحتسب في «القوانين» فقط)
    for lm in LAWNUM_FREE.finditer(text):
        law = f"{int(lm.group('n'))}/{lm.group('y')}"
        if not any(r['law'] == law for r in refs):
            refs.append({'law': law, 'name': CANON.get(law) or lawname_after(text, lm.end()), 'articles': [], 'method': 'explicit', 'raw': lm.group(0)})
    return refs

def extract_ctx(text):
    """نسخة تحدّث «آخر قانون» بالقوانين المذكورة حرًا أيضًا قبل الإحالة السياقية"""
    refs = []
    free = [(lm.start(), f"{int(lm.group('n'))}/{lm.group('y')}", lm.end()) for lm in LAWNUM_FREE.finditer(text)]
    named_pos = []
    for p, k, n in NAMED:
        for nm in re.finditer(rf'(?<![أ-ي])(?:{p})(?![أ-ي])', text):
            if k == '67/1980' and nm.group(0) == 'مدني': continue
            named_pos.append((nm.start(), k, n))
    last = None
    arts_iter = list(ARTSPEC.finditer(text))
    for m in arts_iter:
        arts = parse_arts(m.group('arts'), singular=bool(re.search('مادة$|مادة\\s', m.group('head') + ' ')))
        if not arts: continue
        prior = [(s, k, CANON.get(k) or lawname_after(text, e)) for s, k, e in free if s < m.start()] + [(s, k, n) for s, k, n in named_pos if s < m.start()]
        tail = text[m.end():m.end() + 140]
        law = name = method = None; rawend = m.end()
        lm = LAWNUM.match(tail) or LAWNUM2.match(tail)
        if lm:
            law = f"{int(lm.group('n'))}/{lm.group('y')}"; method = 'explicit'; rawend = m.end() + lm.end()
            name = CANON.get(law) or lawname_after(text, rawend)
        else:
            for rx, k, n in NAMED_RE:
                nm = rx.match(tail)
                if nm:
                    law, name, method = k, n, 'named'; rawend = m.end() + nm.end(); break
            if not law:
                cm = CONTEXT.match(tail)
                if cm:
                    # قانون مذكور بوصفه «معدِّلًا» لا يكون مرجع «هذا القانون/منه»
                    prior = [(s, k, n) for s, k, n in prior if not re.search(r'(?:المعدل|المعدلة|معدل|بتعديل|والمعدل)[^.]{0,25}$', text[max(0, s - 40):s])]
                    cand = [(s, k, n) for s, k, n in prior] + [(s, r['law'], r['name']) for s, r in refs_pos(refs)]
                    if cand:
                        s, law, name = max(cand, key=lambda x: x[0])
                        gap = text[s:m.start()]
                        # لا تُحل الإحالة إن فصل بينها وبين القانون مرجعٌ آخر (لائحة، اتفاقية، عقد، قرار...) أو بعدت المسافة
                        if len(gap) < 600 and not re.search(r'اللائحة|لائحة|الاتفاقية|اتفاقية|العقد|عقد|القرار|قرار|النظام الأساسي|المرسوم الأميري|الدستور', gap[20:]):
                            method = 'context'; rawend = m.end() + cm.end()
                        else:
                            law = name = None
        if law:
            r = {'law': law, 'name': name, 'articles': arts, 'method': method, 'raw': text[m.start():rawend].strip(), '_pos': m.start()}
            refs.append(r)
    for s, law, e in free:
        if not any(r['law'] == law for r in refs):
            refs.append({'law': law, 'name': CANON.get(law) or lawname_after(text, e), 'articles': [], 'method': 'explicit', 'raw': text[s:e], '_pos': s})
    return refs

def refs_pos(refs):
    return [(r['_pos'], r) for r in refs]

